type service struct {
	Name    string
	Repo    string
	RelSpec string
	EnvVar  string
}

var services = []service{
	{"config", "asi-config-service", "src/docs/swagger.json", "ASI_CONFIG_BASE_URL"},
	{"auth", "asi-auth-service", "src/docs/swagger.json", "ASI_AUTH_BASE_URL"},
	{"reporting", "asi-reporting-service", "src/docs/swagger.json", "ASI_REPORTING_BASE_URL"},
	{"reservation", "asi-reservation-service", "docs/swagger.json", "ASI_RESERVATION_BASE_URL"},
}

type schema struct {
	Ref        string             `json:"$ref"`
	Type       string             `json:"type"`
	Properties map[string]*schema `json:"properties"`
	Items      *schema            `json:"items"`
	Required   []string           `json:"required"`
}

type param struct {
	Name        string  `json:"name"`
	In          string  `json:"in"`
	Type        string  `json:"type"`
	Required    bool    `json:"required"`
	Description string  `json:"description"`
	Items       *schema `json:"items"`
	Schema      *schema `json:"schema"`
}

type operation struct {
	OperationID string  `json:"operationId"`
	Summary     string  `json:"summary"`
	Description string  `json:"description"`
	Parameters  []param `json:"parameters"`
}

type spec struct {
	BasePath    string                          `json:"basePath"`
	Paths       map[string]map[string]operation `json:"paths"`
	Definitions map[string]*schema              `json:"definitions"`
}

var httpMethods = map[string]bool{"get": true, "post": true, "put": true, "patch": true, "delete": true, "head": true, "options": true}

func main() {
	root := flag.String("root", "..", "directory containing the sibling service repos")
	specsDir := flag.String("specs-dir", "", "fallback: read <dir>/<service>.swagger.json instead of sibling repos")
	outDir := flag.String("out", "toolregistry/generated", "output directory")
	flag.Parse()

	if err := os.MkdirAll(*outDir, 0o755); err != nil {
		log.Fatal(err)
	}
	if err := writeGo(filepath.Join(*outDir, "client.go"), []byte(clientSrc)); err != nil {
		log.Fatal(err)
	}
	total := 0
	for _, svc := range services {
		p := filepath.Join(*root, svc.Repo, svc.RelSpec)
		if *specsDir != "" {
			p = filepath.Join(*specsDir, svc.Name+".swagger.json")
		}
		b, err := os.ReadFile(p)
		if err != nil {
			log.Printf("warn: %s: %v (skipped)", svc.Name, err)
			continue
		}
		var s spec
		if err := json.Unmarshal(b, &s); err != nil {
			log.Fatalf("%s: parse %s: %v", svc.Name, p, err)
		}
		src, n := generate(svc, &s)
		out := filepath.Join(*outDir, svc.Name+"_tools.go")
		if err := writeGo(out, src); err != nil {
			log.Fatalf("%s: %v", svc.Name, err)
		}
		log.Printf("%-12s %4d tools -> %s", svc.Name, n, out)
		total += n
	}
	log.Printf("total: %d tools", total)
}

func writeGo(path string, src []byte) error {
	f, err := format.Source(src)
	if err != nil {
		_ = os.WriteFile(path+".broken", src, 0o644)
		return fmt.Errorf("gofmt %s: %w", path, err)
	}
	return os.WriteFile(path, f, 0o644)
}

var colonParam = regexp.MustCompile(`:([A-Za-z_][A-Za-z0-9_]*)`)

func generate(svc service, s *spec) ([]byte, int) {
	gen := &fileGen{svc: svc, spec: s, usedTypes: map[string]bool{}}
	var paths []string
	for p := range s.Paths {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	usedFuncs := map[string]bool{}
	var body, meta bytes.Buffer
	n := 0
	prefix := exported(svc.Name)
	for _, p := range paths {
		var methods []string
		for m := range s.Paths[p] {
			if httpMethods[strings.ToLower(m)] {
				methods = append(methods, m)
			}
		}
		sort.Strings(methods)
		for _, m := range methods {
			op := s.Paths[p][m]
			base := op.OperationID
			if base == "" {
				base = m + "_" + p
			}
			fn := unique(prefix+exported(base), usedFuncs)
			toolName := snake(svc.Name + "_" + strings.TrimPrefix(fn, prefix))
			gen.operation(&body, fn, toolName, strings.ToUpper(m), p, op)
			desc := op.Summary
			if desc == "" {
				desc = op.Description
			}
			ro := strings.EqualFold(m, "get") || strings.EqualFold(m, "head")
			fmt.Fprintf(&meta, "{Name: %q, Service: %q, Method: %q, Path: %q, ReadOnly: %v, Description: %q%s},\n",
				toolName, svc.Name, strings.ToUpper(m), swaggerToolPath(s.BasePath, p), ro, oneLine(desc), queryMeta(op.Parameters))
			n++
		}
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by scripts/gen-registry; DO NOT EDIT.\n// Service: %s (base URL env %s)\n\npackage generated\n\n", svc.Name, svc.EnvVar)
	out.WriteString("import (\n\"context\"\n\"net/url\"\n\"strings\"\n\n\"asi-genie-poc/toolregistry\"\n)\n\n")
	out.WriteString("var (\n_ = url.Values{}\n_ = strings.ReplaceAll\n_ = toolregistry.MapToCard\n)\n\n")
	fmt.Fprintf(&out, "// %sService identifies the %s service base URL.\nvar %sService = Service{Name: %q, EnvVar: %q}\n\n", prefix, svc.Name, prefix, svc.Name, svc.EnvVar)
	fmt.Fprintf(&out, "// %sTools lists metadata for every generated %s tool.\nvar %sTools = []ToolMeta{\n%s}\n\nfunc init() { register(%sTools...) }\n\n", prefix, svc.Name, prefix, meta.String(), prefix)
	out.Write(gen.types.Bytes())
	out.Write(body.Bytes())
	return out.Bytes(), n
}

func queryMeta(params []param) string {
	var parts []string
	seen := map[string]bool{}
	for _, pr := range params {
		if pr.In != "query" || seen[pr.Name] {
			continue
		}
		seen[pr.Name] = true
		field := fmt.Sprintf("{Name: %q, Required: %v", pr.Name, pr.Required)
		if all := commaFilterValues(pr.Description); len(all) > 0 {
			quoted := make([]string, len(all))
			for i, v := range all {
				quoted[i] = fmt.Sprintf("%q", v)
			}
			field += fmt.Sprintf(", AllValues: []string{%s}", strings.Join(quoted, ", "))
		}
		parts = append(parts, field+"}")
	}
	if len(parts) == 0 {
		return ""
	}
	return ", Query: []QueryParam{" + strings.Join(parts, ", ") + "}"
}

var (
	filterValuesRe   = regexp.MustCompile(`(?i)filter\s*\(([^)]+)\)`)
	commaSeparatedRe = regexp.MustCompile(`(?i)^comma[-\s]separated:?\s*`)
	enumIdentifierRe = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*$`)
)

// An unset comma-separated filter makes some reports match nothing, so callers send every documented value. Nil unless the list is an exhaustive identifier enum.
func commaFilterValues(desc string) []string {
	lower := strings.ToLower(desc)
	if !strings.Contains(lower, "comma-separated") && !strings.Contains(lower, "comma separated") {
		return nil
	}
	m := filterValuesRe.FindStringSubmatch(desc)
	if m == nil {
		return nil
	}
	group := commaSeparatedRe.ReplaceAllString(m[1], "")
	raw := strings.Split(group, ",")
	vals := make([]string, 0, len(raw))
	for _, v := range raw {
		v = strings.TrimSpace(v)
		if !enumIdentifierRe.MatchString(v) || strings.EqualFold(v, "etc") {
			return nil // not an exhaustive enum
		}
		vals = append(vals, v)
	}
	if len(vals) < 2 {
		return nil
	}
	return vals
}

type fileGen struct {
	svc       service
	spec      *spec
	types     bytes.Buffer
	usedTypes map[string]bool
}

type field struct {
	GoName, GoType, JSON, Tag, In string
	Required                      bool
}

func (g *fileGen) operation(w *bytes.Buffer, fn, toolName, method, path string, op operation) {
	// Specs sometimes use ":id" and omit the parameter declaration.
	path = colonParam.ReplaceAllString(path, "{$1}")
	used := map[string]bool{}
	var fields []field
	declared := map[string]bool{}
	hasForm := false
	for _, pr := range op.Parameters {
		if pr.In == "path" {
			declared[pr.Name] = true
		}
	}
	for _, m := range regexp.MustCompile(`\{([^}]+)\}`).FindAllStringSubmatch(path, -1) {
		if !declared[m[1]] {
			op.Parameters = append(op.Parameters, param{Name: m[1], In: "path", Type: "string", Required: true})
		}
	}
	usedTags := map[string]bool{}
	for _, pr := range op.Parameters {
		f := field{JSON: pr.Name, In: pr.In, Required: pr.Required}
		tag := pr.Name
		if usedTags[tag] {
			tag = pr.Name + "_" + pr.In // path and query can share a name
		}
		usedTags[tag] = true
		f.Tag = tag
		f.GoName = unique(exported(pr.Name), used)
		switch pr.In {
		case "body":
			f.GoName = unique("Body", used)
			f.GoType = g.bodyType(fn, pr.Schema)
		case "formData":
			hasForm = true
			if pr.Type == "file" {
				f.GoType = "[]byte // file upload: not sent by generated code"
			} else {
				f.GoType = "string"
			}
		default:
			f.GoType = primType(pr.Type, pr.Items)
		}
		fields = append(fields, f)
	}

	desc := op.Summary
	if desc == "" {
		desc = op.Description
	}
	fmt.Fprintf(w, "// %sInput is the input for %s %s.\ntype %sInput struct {\n", fn, method, path, fn)
	for _, f := range fields {
		omit := ",omitempty"
		if f.Required {
			omit = ""
		}
		typ, comment := f.GoType, ""
		if i := strings.Index(typ, " //"); i >= 0 {
			typ, comment = typ[:i], typ[i:]
		}
		fmt.Fprintf(w, "%s %s `json:\"%s%s\" in:\"%s\"`%s\n", f.GoName, typ, f.Tag, omit, f.In, comment)
	}
	w.WriteString("}\n\n")

	toolPath := swaggerToolPath(g.spec.BasePath, path)
	fmt.Fprintf(w, "// %s calls %s %s.\n// %s\nfunc %s(ctx context.Context, c *Client, in %sInput) (any, error) {\n", fn, method, toolPath, oneLine(desc), fn, fn)
	fmt.Fprintf(w, "const tool = %q\n", toolName)
	w.WriteString("if err := toolregistry.CheckPermission(ctx, tool, toolregistry.RoleFromContext(ctx)); err != nil {\nreturn nil, err\n}\n")
	fmt.Fprintf(w, "p := %q\n", toolPath)
	w.WriteString("q := url.Values{}\nh := map[string]string{}\nform := url.Values{}\nvar body any\n_, _, _ = q, h, form\n")
	for _, f := range fields {
		switch f.In {
		case "path":
			fmt.Fprintf(w, "p = strings.ReplaceAll(p, %q, url.PathEscape(toString(in.%s)))\n", "{"+f.JSON+"}", f.GoName)
		case "query":
			fmt.Fprintf(w, "addQuery(q, %q, in.%s)\n", f.JSON, f.GoName)
		case "header":
			fmt.Fprintf(w, "if s := toString(in.%s); s != \"\" {\nh[%q] = s\n}\n", f.GoName, f.JSON)
		case "body":
			fmt.Fprintf(w, "body = in.%s\n", f.GoName)
		case "formData":
			if !strings.HasPrefix(f.GoType, "[]byte") {
				fmt.Fprintf(w, "if in.%s != \"\" {\nform.Set(%q, in.%s)\n}\n", f.GoName, f.JSON, f.GoName)
			}
		}
	}
	if hasForm {
		w.WriteString("if len(form) > 0 && body == nil {\nbody = form\n}\n")
	}
	fmt.Fprintf(w, "resp, err := c.Do(ctx, %sService, %q, p, q, h, body)\nif err != nil {\nreturn nil, err\n}\nreturn toolregistry.MapToCard(tool, resp)\n}\n\n", exported(g.svc.Name), method)
}

func (g *fileGen) bodyType(fn string, s *schema) string {
	if s == nil {
		return "map[string]any"
	}
	if s.Type == "array" {
		return "[]any"
	}
	if s.Ref == "" {
		return "map[string]any"
	}
	defName := strings.TrimPrefix(s.Ref, "#/definitions/")
	def, ok := g.spec.Definitions[defName]
	if !ok || len(def.Properties) == 0 {
		return "map[string]any"
	}
	tn := exported(defName)
	if g.usedTypes[tn] {
		return tn
	}
	g.usedTypes[tn] = true
	req := map[string]bool{}
	for _, r := range def.Required {
		req[r] = true
	}
	var names []string
	for k := range def.Properties {
		names = append(names, k)
	}
	sort.Strings(names)
	used := map[string]bool{}
	fmt.Fprintf(&g.types, "// %s mirrors definition %q.\ntype %s struct {\n", tn, defName, tn)
	for _, k := range names {
		p := def.Properties[k]
		typ := "any"
		if p != nil && p.Ref == "" {
			switch p.Type {
			case "string", "integer", "number", "boolean":
				typ = primType(p.Type, nil)
			case "array":
				typ = "[]any"
			case "object":
				typ = "map[string]any"
			}
		}
		omit := ",omitempty"
		if req[k] {
			omit = ""
		}
		fmt.Fprintf(&g.types, "%s %s `json:\"%s%s\"`\n", unique(exported(k), used), typ, k, omit)
	}
	g.types.WriteString("}\n\n")
	return tn
}

func primType(t string, items *schema) string {
	switch t {
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		if items != nil {
			return "[]" + primType(items.Type, nil)
		}
		return "[]string"
	}
	return "string"
}

func joinPath(base, p string) string {
	return strings.TrimSuffix(base, "/") + p
}

// Reservation specs mix paths that already include basePath with paths that do not.
func swaggerToolPath(basePath, p string) string {
	bp := strings.TrimSuffix(basePath, "/")
	if bp == "" || bp == "/" {
		return p
	}
	for strings.HasPrefix(p, bp+bp+"/") {
		p = strings.TrimPrefix(p, bp)
	}
	if strings.HasPrefix(p, bp+"/") || p == bp {
		return p
	}
	return joinPath(basePath, p)
}

func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > 160 {
		s = s[:160] + "..."
	}
	return s
}

func unique(name string, used map[string]bool) string {
	n, i := name, 2
	for used[n] {
		n = fmt.Sprintf("%s%d", name, i)
		i++
	}
	used[n] = true
	return n
}

var goKeywords = map[string]bool{"type": true, "func": true, "range": true, "map": true}

func exported(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			up = true
			continue
		}
		if up {
			b.WriteRune(unicode.ToUpper(r))
			up = false
		} else {
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "X" + out
	}
	return out
}

func snake(s string) string {
	var b strings.Builder
	rs := []rune(s)
	for i, r := range rs {
		if unicode.IsUpper(r) {
			if i > 0 && rs[i-1] != '_' && (unicode.IsLower(rs[i-1]) || unicode.IsDigit(rs[i-1]) || (i+1 < len(rs) && unicode.IsLower(rs[i+1]))) {
				b.WriteRune('_')
			}
			b.WriteRune(unicode.ToLower(r))
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

const clientSrc = `// Code generated by scripts/gen-registry; DO NOT EDIT.

// Package generated contains typed HTTP tools generated from the ASI Swagger specs.
package generated

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"strings"
	"time"

	"asi-genie-poc/internal/logx"
	"asi-genie-poc/toolregistry"
)

// Service identifies an ASI backend; its base URL comes from EnvVar.
type Service struct {
	Name   string
	EnvVar string
}

// ToolMeta describes one generated tool.
type ToolMeta struct {
	Name        string
	Service     string
	Method      string
	Path        string
	ReadOnly    bool
	Description string
	Query       []QueryParam
}

// QueryParam is one query-string parameter a tool accepts.
type QueryParam struct {
	Name     string
	Required bool
	// AllValues is the full value set for a comma-separated filter param
	// (from its swagger description), when the spec documents one. Some
	// reports return an empty result when such a param is left unset, so the
	// planner defaults to sending every value instead of none.
	AllValues []string
}

var allTools []ToolMeta

func register(t ...ToolMeta) { allTools = append(allTools, t...) }

// AllTools returns metadata for every generated tool across services.
func AllTools() []ToolMeta { return append([]ToolMeta(nil), allTools...) }

// joinURL appends path to base without repeating a base path the spec already
// put in the path (e.g. base ".../api/v1" + "/api/v1/x", or Swagger's doubled
// "/api/v1/api/v1/x").
func joinURL(base, path string) string {
	if pu, err := url.Parse(base); err == nil && pu.Path != "" && pu.Path != "/" {
		bp := strings.TrimSuffix(pu.Path, "/")
		for strings.HasPrefix(path, bp+bp+"/") {
			path = strings.TrimPrefix(path, bp)
		}
		if strings.HasPrefix(path, bp+"/") {
			path = strings.TrimPrefix(path, bp)
		}
	}
	return base + path
}

// logASI prints one "── ASI ▶ METHOD path" block (bodies at LOG_LEVEL=debug).
func logASI(ctx context.Context, s Service, method, fullURL string, sent []byte, status int, data []byte, err error, d time.Duration) {
	title := method + " " + fullURL
	if pu, perr := url.Parse(fullURL); perr == nil {
		title = method + " " + pu.Path
	}
	st := "ERROR"
	if status > 0 {
		st = fmt.Sprintf("HTTP %d", status)
	}
	fields := []logx.Field{logx.F("tool", logx.Tool(ctx)), logx.F("service", s.Name), logx.F("url", fullURL)}
	if err != nil {
		fields = append(fields, logx.F("error", err))
	}
	fields = append(fields, logx.B("request body", sent), logx.B("response body", data))
	logx.Block("ASI", title, st, d, err == nil && status > 0 && status < 400, fields...)
}

// Client is the shared HTTP client for all generated tools.
type Client struct {
	HTTP     *http.Client
	BaseURLs map[string]string // overrides env, keyed by service name
	Token    string            // fallback when no token is in the context
}

// NewClient returns a Client with a 30s timeout.
func NewClient() *Client {
	return &Client{HTTP: &http.Client{Timeout: 30 * time.Second}, BaseURLs: map[string]string{}}
}

func (c *Client) baseURL(s Service) (string, error) {
	if u := c.BaseURLs[s.Name]; u != "" {
		return strings.TrimSuffix(u, "/"), nil
	}
	if u := os.Getenv(s.EnvVar); u != "" {
		return strings.TrimSuffix(u, "/"), nil
	}
	return "", fmt.Errorf("base URL for %s not set (env %s)", s.Name, s.EnvVar)
}

// Do performs the request and returns the raw response body.
func (c *Client) Do(ctx context.Context, s Service, method, path string, q url.Values, headers map[string]string, body any) ([]byte, error) {
	base, err := c.baseURL(s)
	if err != nil {
		return nil, err
	}
	u := joinURL(base, path)
	if len(q) > 0 {
		u += "?" + q.Encode()
	}
	var rdr io.Reader
	var sent []byte
	contentType := ""
	switch b := body.(type) {
	case nil:
	case url.Values:
		sent = []byte(b.Encode())
		rdr, contentType = bytes.NewReader(sent), "application/x-www-form-urlencoded"
	default:
		j, err := json.Marshal(b)
		if err != nil {
			return nil, err
		}
		sent = j
		rdr, contentType = bytes.NewReader(j), "application/json"
	}
	start := time.Now()
	req, err := http.NewRequestWithContext(ctx, method, u, rdr)
	if err != nil {
		return nil, err
	}
	if contentType != "" {
		req.Header.Set("Content-Type", contentType)
	}
	req.Header.Set("Accept", "application/json")
	tok := toolregistry.TokenFromContext(ctx)
	if tok == "" {
		tok = c.Token
	}
	if tok != "" {
		req.Header.Set("Authorization", "Bearer "+tok)
	}
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	hc := c.HTTP
	if hc == nil {
		hc = http.DefaultClient
	}
	resp, err := hc.Do(req)
	if err != nil {
		logASI(ctx, s, method, u, sent, 0, nil, err, time.Since(start))
		return nil, err
	}
	defer resp.Body.Close()
	data, err := io.ReadAll(resp.Body)
	logASI(ctx, s, method, u, sent, resp.StatusCode, data, err, time.Since(start))
	if err != nil {
		return nil, err
	}
	if resp.StatusCode >= 400 {
		return data, fmt.Errorf("%s %s: HTTP %d: %s", method, path, resp.StatusCode, strings.TrimSpace(string(data)))
	}
	return data, nil
}

func toString(v any) string {
	switch x := v.(type) {
	case string:
		return x
	case nil:
		return ""
	default:
		return fmt.Sprint(x)
	}
}

func addQuery(q url.Values, key string, v any) {
	switch x := v.(type) {
	case string:
		if x != "" {
			q.Set(key, x)
		}
	case []string:
		for _, s := range x {
			q.Add(key, s)
		}
	case []int64:
		for _, n := range x {
			q.Add(key, fmt.Sprint(n))
		}
	case []float64:
		for _, n := range x {
			q.Add(key, fmt.Sprint(n))
		}
	case []bool:
		for _, b := range x {
			q.Add(key, fmt.Sprint(b))
		}
	case int64:
		if x != 0 {
			q.Set(key, fmt.Sprint(x))
		}
	case float64:
		if x != 0 {
			q.Set(key, fmt.Sprint(x))
		}
	case bool:
		if x {
			q.Set(key, "true")
		}
	}
}
`
