// Command gen-intents reads the Genie scenario catalogue (Scenarios.csv) and
// emits internal/intents/catalog_gen.go with every Phase 1 (In/Partial) scenario.
//
//	go run ./scripts/gen-intents [Scenarios.csv] [internal/intents/catalog_gen.go]
//
// scripts/gen-intents/gen_intents.py produces identical output without Go.
package main

import (
	"bytes"
	"encoding/csv"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"regexp"
	"strings"
)

var tripleRe = regexp.MustCompile(`([^→()]+?)\s*→\s*([^→()]+?)\s*→\s*(READ|CREATE|UPDATE|DELETE|RESOLVE)`)

func q(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

type req struct {
	mod, feat, perm string
	optional        bool
}

func parseReqs(rbac string) []req {
	var out []req
	for _, m := range tripleRe.FindAllStringSubmatchIndex(rbac, -1) {
		before := rbac[:m[0]]
		depth := strings.Count(before, "(") - strings.Count(before, ")")
		raw := strings.TrimSpace(rbac[m[2]:m[3]])
		alt := strings.HasPrefix(raw, "/") || strings.HasPrefix(strings.ToLower(raw), "or ")
		mod := strings.TrimSpace(strings.TrimLeft(raw, "+/ "))
		for _, pre := range []string{"or ", "and ", "fails "} {
			if strings.HasPrefix(strings.ToLower(mod), pre) {
				mod = strings.TrimSpace(mod[len(pre):])
			}
		}
		out = append(out, req{mod, strings.TrimSpace(rbac[m[4]:m[5]]), rbac[m[6]:m[7]], depth > 0 || alt})
	}
	return out
}

func main() {
	src, dst := "specs/catalogue/genie-catalogue/Scenarios.csv", "internal/intents/catalog_gen.go"
	if len(os.Args) > 1 {
		src = os.Args[1]
	}
	if len(os.Args) > 2 {
		dst = os.Args[2]
	}
	f, err := os.Open(src)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	r := csv.NewReader(f)
	r.FieldsPerRecord = -1
	r.LazyQuotes = true
	rows, err := r.ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	if len(rows) == 0 {
		log.Fatal("empty csv")
	}
	col := map[string]int{}
	for i, h := range rows[0] {
		col[strings.TrimPrefix(strings.TrimSpace(h), "\ufeff")] = i
	}
	get := func(row []string, name string) string {
		i, ok := col[name]
		if !ok || i >= len(row) {
			return ""
		}
		return strings.TrimSpace(row[i])
	}
	var b strings.Builder
	b.WriteString("// Code generated by scripts/gen-intents from Scenarios.csv; DO NOT EDIT.\n\npackage intents\n\n")
	b.WriteString("// Catalog lists every Phase 1 (In/Partial) scenario from the Genie scenario catalogue.\nvar Catalog = []Intent{\n")
	n := 0
	for _, row := range rows[1:] {
		scope := get(row, "Phase 1 scope")
		if !strings.HasPrefix(scope, "In") && !strings.HasPrefix(scope, "Partial") {
			continue
		}
		n++
		var ex []string
		for _, e := range strings.Split(get(row, "Example question(s)"), "|") {
			if e = strings.TrimSpace(e); e != "" {
				ex = append(ex, q(e))
			}
		}
		rbac := get(row, "RBAC check (Module → Feature → Permission)")
		var rq []string
		for _, x := range parseReqs(rbac) {
			rq = append(rq, fmt.Sprintf("{Module: %s, Feature: %s, Permission: %s, Optional: %t}", q(x.mod), q(x.feat), q(x.perm), x.optional))
		}
		b.WriteString("\t{\n")
		fmt.Fprintf(&b, "\t\tScenarioID: %s, ID: %s, Module: %s, Category: %s,\n", q(get(row, "ID")), q(get(row, "Intent / capability id")), q(get(row, "Module")), q(get(row, "Category")))
		fmt.Fprintf(&b, "\t\tExamples:     []string{%s},\n", strings.Join(ex, ", "))
		fmt.Fprintf(&b, "\t\tHandling:     %s,\n", q(get(row, "Phase 1 - how it is handled")))
		fmt.Fprintf(&b, "\t\tUserSees:     %s,\n", q(get(row, "Phase 1 - what the user sees")))
		fmt.Fprintf(&b, "\t\tResponseType: %s, Scope: %s, Priority: %s,\n", q(get(row, "Response type")), q(scope), q(get(row, "Priority")))
		fmt.Fprintf(&b, "\t\tRBAC:         %s,\n", q(rbac))
		fmt.Fprintf(&b, "\t\tRequirements: []Requirement{%s},\n", strings.Join(rq, ", "))
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	if err := os.WriteFile(dst, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d intents to %s\n", n, dst)
}
