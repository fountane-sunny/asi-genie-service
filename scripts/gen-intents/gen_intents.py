#!/usr/bin/env python3
"""Python twin of scripts/gen-intents/main.go (same output). Usage:
  python3 scripts/gen-intents/gen_intents.py [specs/catalogue/genie-catalogue/Scenarios.csv] [internal/intents/catalog_gen.go]
"""
import csv, json, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else "specs/catalogue/genie-catalogue/Scenarios.csv"
dst = sys.argv[2] if len(sys.argv) > 2 else "internal/intents/catalog_gen.go"
TRIPLE = re.compile(r"([^→()]+?)\s*→\s*([^→()]+?)\s*→\s*(READ|CREATE|UPDATE|DELETE|RESOLVE)")

def q(s):  # Go string literal (json escaping is valid Go for these strings)
    return json.dumps(s, ensure_ascii=False)

def reqs(rbac):
    out = []
    for m in TRIPLE.finditer(rbac):
        depth = rbac[: m.start()].count("(") - rbac[: m.start()].count(")")
        raw = m.group(1).strip()
        alt = raw.startswith("/") or raw.lower().startswith("or ")  # "A / B" or "A or B" alternatives
        mod = raw.lstrip("+/ ").strip()
        for pre in ("or ", "and ", "fails "):
            if mod.lower().startswith(pre):
                mod = mod[len(pre):].strip()
        out.append((mod, m.group(2).strip(), m.group(3), depth > 0 or alt))
    return out

rows = list(csv.DictReader(open(src, encoding="utf-8-sig")))
lines = [
    "// Code generated by scripts/gen-intents from Scenarios.csv; DO NOT EDIT.",
    "",
    "package intents",
    "",
    "// Catalog lists every Phase 1 (In/Partial) scenario from the Genie scenario catalogue.",
    "var Catalog = []Intent{",
]
n = 0
for r in rows:
    scope = r["Phase 1 scope"].strip()
    if not (scope.startswith("In") or scope.startswith("Partial")):
        continue
    n += 1
    ex = [e.strip() for e in r["Example question(s)"].split("|") if e.strip()]
    rq = ", ".join(
        "{Module: %s, Feature: %s, Permission: %s, Optional: %s}" % (q(a), q(b), q(c), "true" if o else "false")
        for a, b, c, o in reqs(r["RBAC check (Module → Feature → Permission)"])
    )
    lines.append("\t{")
    lines.append("\t\tScenarioID: %s, ID: %s, Module: %s, Category: %s," % (
        q(r["ID"].strip()), q(r["Intent / capability id"].strip()), q(r["Module"].strip()), q(r["Category"].strip())))
    lines.append("\t\tExamples:     []string{%s}," % ", ".join(q(e) for e in ex))
    lines.append("\t\tHandling:     %s," % q(r["Phase 1 - how it is handled"].strip()))
    lines.append("\t\tUserSees:     %s," % q(r["Phase 1 - what the user sees"].strip()))
    lines.append("\t\tResponseType: %s, Scope: %s, Priority: %s," % (
        q(r["Response type"].strip()), q(scope), q(r["Priority"].strip())))
    lines.append("\t\tRBAC:         %s," % q(r["RBAC check (Module → Feature → Permission)"].strip()))
    lines.append("\t\tRequirements: []Requirement{%s}," % rq)
    lines.append("\t},")
lines.append("}")
open(dst, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"wrote {n} intents to {dst}")
